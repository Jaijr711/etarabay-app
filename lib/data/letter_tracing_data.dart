import 'package:flutter/material.dart';

/// One character the child can trace.
///
/// This used to carry a `points` list as well — about forty Offsets tracing
/// the character's outline, which the freehand mechanic scored a child's
/// drawing against. That mechanic never ran (every character has stroke data,
/// so the screen always chose drag-to-fill) and has been removed, so the
/// points went with it. The shapes now live in `uppercaseStrokes`,
/// `lowercaseStrokes` and `numberStrokes` as ordered stroke skeletons: the
/// same outlines, split into the separate pen strokes a child makes and in
/// the order they make them.
class LetterData {
  final String letter;
  final String sound;
  final String example;
  final Color color;
  final int difficulty;

  const LetterData({
    required this.letter,
    required this.sound,
    required this.example,
    required this.color,
    required this.difficulty,
  });
}

